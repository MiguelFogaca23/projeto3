DROP TABLE IF EXISTS public.ficha_catalografica, public.livro, public.autor, public.editora CASCADE;

CREATE TABLE public.autor (
    id_autor integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_autor varchar(120) NOT NULL,
    nacionalidade_autor varchar(60)
);

CREATE TABLE public.editora (
    id_editora integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_editora varchar(120) NOT NULL,
    cidade_editora varchar(80),
    site_editora varchar(180)
);

CREATE TABLE public.livro (
    id_livro integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo_livro varchar(180) NOT NULL,
    isbn_livro varchar(20),
    ano_publicacao_livro integer,
    numero_edicao_livro integer,
    autor_id_autor integer NOT NULL REFERENCES public.autor(id_autor),
    editora_id_editora integer REFERENCES public.editora(id_editora),
    CONSTRAINT livro_ano_check CHECK (ano_publicacao_livro IS NULL OR ano_publicacao_livro BETWEEN 1000 AND 3000),
    CONSTRAINT livro_edicao_check CHECK (numero_edicao_livro IS NULL OR numero_edicao_livro > 0)
);

CREATE TABLE public.ficha_catalografica (
    livro_id_livro integer PRIMARY KEY REFERENCES public.livro(id_livro) ON DELETE CASCADE,
    assunto_ficha varchar(180),
    palavras_chave_ficha text,
    descricao_fisica_ficha varchar(180),
    notas_ficha text
);

